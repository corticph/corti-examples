import type { Corti, CortiClient } from "@corti/sdk";
import { describe, expect, it, vi } from "vitest";
import {
  deduplicateTemplates,
  describeDocumentsError,
  documentSections,
  findDefaultTemplate,
  generateFromText,
} from "./corti-documents";

function makeDoc(
  stringDocument: Record<string, string>,
  sections?: { sectionId: string; heading: string }[],
): Corti.GuidedEphemeralDocument {
  return {
    name: "Test",
    templateId: "t-1",
    templateVersionId: "v-1",
    outputLanguage: "en",
    stringDocument,
    sections,
    labels: [],
  } as Corti.GuidedEphemeralDocument;
}

function makeTemplate(overrides: Partial<Corti.GuidedTemplate>): Corti.GuidedTemplate {
  return {
    id: "t-1",
    inheritedFromId: null,
    autoGenerated: false,
    source: undefined,
    name: "SOAP Note",
    description: undefined,
    languages: ["en"],
    regions: ["US"],
    specialties: [],
    labels: [],
    createdBy: undefined,
    createdAt: new Date("2026-01-01T00:00:00Z"),
    updatedAt: new Date("2026-01-01T00:00:00Z"),
    deletedAt: null,
    publishedVersion: undefined,
    ...overrides,
  } as Corti.GuidedTemplate;
}

describe("findDefaultTemplate", () => {
  const templates = [
    makeTemplate({ id: "t-1", name: "SOAP Note" }),
    makeTemplate({ id: "t-2", name: "Discharge Summary" }),
    makeTemplate({ id: "t-3", name: "Referral Letter" }),
  ];

  it("matches by keyword substring", () => {
    expect(findDefaultTemplate(templates, "soap")?.id).toBe("t-1");
    expect(findDefaultTemplate(templates, "discharge")?.id).toBe("t-2");
  });

  it("falls back to first template when no keyword matches", () => {
    expect(findDefaultTemplate(templates, "nonexistent")?.id).toBe("t-1");
  });

  it("returns undefined for empty list", () => {
    expect(findDefaultTemplate([], "soap")).toBeUndefined();
  });
});

describe("deduplicateTemplates", () => {
  it("returns single template unchanged", () => {
    const single = [makeTemplate({ id: "t-1" })];
    expect(deduplicateTemplates(single)).toEqual(single);
  });

  it("prefers non-auto-generated over auto-generated with same name", () => {
    const templates = [
      makeTemplate({ id: "auto", name: "SOAP Note", autoGenerated: true }),
      makeTemplate({ id: "manual", name: "SOAP Note", autoGenerated: false }),
    ];
    const result = deduplicateTemplates(templates);
    expect(result).toHaveLength(1);
    expect(result[0].id).toBe("manual");
  });

  it("prefers non-inherited over inherited when both autoGenerated", () => {
    const templates = [
      makeTemplate({
        id: "inherited",
        name: "SOAP Note",
        autoGenerated: true,
        inheritedFromId: "parent-1",
      }),
      makeTemplate({
        id: "original",
        name: "SOAP Note",
        autoGenerated: true,
        inheritedFromId: null,
      }),
    ];
    const result = deduplicateTemplates(templates);
    expect(result).toHaveLength(1);
    expect(result[0].id).toBe("original");
  });

  it("uses updatedAt as tiebreaker when scores are equal", () => {
    const older = makeTemplate({
      id: "older",
      name: "SOAP Note",
      updatedAt: new Date("2026-01-01T00:00:00Z"),
    });
    const newer = makeTemplate({
      id: "newer",
      name: "SOAP Note",
      updatedAt: new Date("2026-06-01T00:00:00Z"),
    });
    const result = deduplicateTemplates([older, newer]);
    expect(result).toHaveLength(1);
    expect(result[0].id).toBe("newer");
  });

  it("keeps both variants when scores tie and specialties differ", () => {
    const templates = [
      makeTemplate({ id: "a", name: "ED Note", specialties: ["emergency"] }),
      makeTemplate({ id: "b", name: "ED Note", specialties: ["cardiology"] }),
    ];
    const result = deduplicateTemplates(templates);
    expect(result).toHaveLength(2);
  });

  it("handles case-insensitive name grouping", () => {
    const templates = [
      makeTemplate({ id: "a", name: "SOAP Note" }),
      makeTemplate({ id: "b", name: "soap note" }),
    ];
    const result = deduplicateTemplates(templates);
    expect(result).toHaveLength(1);
  });
});

describe("documentSections", () => {
  it("maps sectionId to heading using the sections array", () => {
    const doc = makeDoc({ "s-1": "Patient presents with…", "s-2": "Assessment…" }, [
      { sectionId: "s-1", heading: "Subjective" },
      { sectionId: "s-2", heading: "Assessment" },
    ]);
    expect(documentSections(doc)).toEqual([
      ["Subjective", "Patient presents with…"],
      ["Assessment", "Assessment…"],
    ]);
  });

  it("filters out empty sections", () => {
    const doc = makeDoc({ "s-1": "Content", "s-2": "" }, [
      { sectionId: "s-1", heading: "Subjective" },
      { sectionId: "s-2", heading: "Objective" },
    ]);
    expect(documentSections(doc)).toEqual([["Subjective", "Content"]]);
  });

  it("falls back to raw keys when sections is absent", () => {
    const doc = makeDoc({ "s-1": "Content here" });
    expect(documentSections(doc)).toEqual([["s-1", "Content here"]]);
  });

  it("falls back to raw keys when sections is empty", () => {
    const doc = makeDoc({ "s-1": "Content" }, []);
    expect(documentSections(doc)).toEqual([["s-1", "Content"]]);
  });

  it("handles missing sectionId in stringDocument", () => {
    const doc = makeDoc({ "s-1": "Content" }, [
      { sectionId: "s-1", heading: "Subjective" },
      { sectionId: "s-2", heading: "Objective" },
    ]);
    expect(documentSections(doc)).toEqual([["Subjective", "Content"]]);
  });
});

describe("generateFromText", () => {
  it("calls client.documents.generate with correct payload", async () => {
    const generate = vi.fn().mockResolvedValue({
      document: { name: "Test", stringDocument: {} },
      usageInfo: { creditsConsumed: 1 },
    });
    const client = {
      documents: { generate },
    } as unknown as CortiClient;

    await generateFromText(client, "tpl-1", "Some clinical text", "en");

    expect(generate).toHaveBeenCalledWith({
      outputLanguage: "en",
      templateRef: { templateId: "tpl-1" },
      context: [{ type: "text", text: "Some clinical text" }],
    });
  });

  it("returns the SDK response", async () => {
    const response = {
      document: { name: "Test", stringDocument: {} },
      usageInfo: { creditsConsumed: 1 },
    };
    const generate = vi.fn().mockResolvedValue(response);
    const client = {
      documents: { generate },
    } as unknown as CortiClient;

    const result = await generateFromText(client, "tpl-1", "text", "da");
    expect(result).toBe(response);
  });
});

describe("describeDocumentsError", () => {
  it("returns a friendly 403 message", () => {
    const error = new Error("HTTP 403: Forbidden");
    expect(describeDocumentsError(error)).toBe(
      "Document generation failed (403). Verify the token scope, tenant, and environment.",
    );
  });

  it("passes through non-403 error messages", () => {
    expect(describeDocumentsError(new Error("Something else"))).toBe("Something else");
  });

  it("handles non-Error values", () => {
    expect(describeDocumentsError("string error")).toBe("string error");
  });
});
